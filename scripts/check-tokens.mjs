/**
 * Reads tokens from src/styles/tokens.css, then writes src/styles/tokens.generated.ts
 * and updates the color table in DESIGN.md. One source of values, so the design
 * table can never drift from the CSS.
 *
 * Run: node scripts/check-tokens.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const root = new URL('../', import.meta.url)
const cssPath = fileURLToPath(new URL('src/styles/tokens.css', root))
const outPath = fileURLToPath(new URL('src/styles/tokens.generated.ts', root))
const designPath = fileURLToPath(new URL('DESIGN.md', root))
const manifestPath = fileURLToPath(new URL('public/manifest.webmanifest', root))

const css = readFileSync(cssPath, 'utf8')

function blockAfter(marker) {
  const start = css.search(new RegExp(`^${marker.replace(/[.*+?^$()|[\]\\]/g, '\\$&')}\\s*{`, 'm'))
  if (start === -1) throw new Error(`Block not found: ${marker}`)

  let depth = 0
  let bodyStart = -1
  for (let i = start; i < css.length; i += 1) {
    const char = css[i]
    if (char === '{') {
      depth += 1
      if (depth === 1) bodyStart = i + 1
      continue
    }
    if (char === '}') {
      depth -= 1
      if (depth === 0) return css.slice(bodyStart, i)
    }
  }
  throw new Error(`Unclosed block: ${marker}`)
}

function varsIn(block) {
  const vars = {}
  for (const match of block.matchAll(/--([a-z0-9-]+)\s*:\s*(#[0-9a-fA-F]{3,8})\s*;/g)) {
    vars[match[1]] = match[2].toLowerCase()
  }
  return vars
}

const light = varsIn(blockAfter(':root'))
const dark = varsIn(blockAfter("[data-theme='dark']"))

// --accent-focus deliberately repeats the literal --accent (a var() alias cannot
// lock the value once the data-phase attribute overrides --accent). This duplication
// is guarded: if one changes without the other, throw.
for (const [theme, vars] of [
  ['light', light],
  ['dark', dark],
]) {
  if (vars['accent-focus'] !== vars.accent) {
    throw new Error(`--accent-focus is not identical to --accent in the ${theme} theme`)
  }
}

const need = (vars, name, theme) => {
  const value = vars[name]
  if (!value) throw new Error(`Token --${name} missing in the ${theme} theme`)
  return value
}

const toEntry = (vars, theme) => ({
  paper: need(vars, 'paper', theme),
  paperRaised: need(vars, 'paper-raised', theme),
  paperSunken: need(vars, 'paper-sunken', theme),
  ink: need(vars, 'ink', theme),
  inkMuted: need(vars, 'ink-muted', theme),
  inkFaint: need(vars, 'ink-faint', theme),
  line: need(vars, 'line', theme),
  lineStrong: need(vars, 'line-strong', theme),
  inkInverse: need(vars, 'ink-inverse', theme),
  accentFocus: need(vars, 'accent', theme),
  accentBreak: need(vars, 'accent-break', theme),
  accentLongbreak: need(vars, 'accent-longbreak', theme),
})

const tokens = { light: toEntry(light, 'light'), dark: toEntry(dark, 'dark') }

const rows = [
  ['paper', 'paper', 'Warm paper'],
  ['paper-raised', 'paperRaised', 'Raised surface'],
  ['paper-sunken', 'paperSunken', 'Status bar'],
  ['ink', 'ink', 'Primary ink'],
  ['ink-muted', 'inkMuted', 'Secondary text'],
  ['line', 'line', 'Divider line'],
  ['line-strong', 'lineStrong', 'Interactive border (WCAG 1.4.11)'],
  ['accent', 'accentFocus', 'Focus accent'],
  ['accent-focus', 'accentFocus', 'Chart accent that ignores the phase'],
  ['accent-break', 'accentBreak', 'Break accent'],
  ['accent-longbreak', 'accentLongbreak', 'Long break accent'],
]

const table = [
  '| Token | Light | Dark | Notes |',
  '| --- | --- | --- | --- |',
  ...rows.map(
    ([name, key, note]) =>
      `| \`--${name}\` | \`${tokens.light[key]}\` | \`${tokens.dark[key]}\` | ${note} |`,
  ),
].join('\n')

const design = readFileSync(designPath, 'utf8')
const begin = '<!-- tokens:begin -->'
const end = '<!-- tokens:end -->'
const block = `${begin}\n${table}\n${end}`
const next = design.includes(begin)
  ? design.replace(new RegExp(`${begin}[\\s\\S]*?${end}`), block)
  : design
if (!design.includes(begin)) {
  throw new Error(`DESIGN.md has no ${begin} / ${end} markers`)
}
writeFileSync(designPath, next)

writeFileSync(
  outPath,
  `/**
 * Generated by scripts/check-tokens.mjs from src/styles/tokens.css.
 * Do not edit by hand; change the tokens and run \`node scripts/check-tokens.mjs\`.
 */

export interface ThemeTokens {
  paper: string
  paperRaised: string
  paperSunken: string
  ink: string
  inkMuted: string
  inkFaint: string
  line: string
  lineStrong: string
  inkInverse: string
  accentFocus: string
  accentBreak: string
  accentLongbreak: string
}

export const TOKENS: Record<'light' | 'dark', ThemeTokens> = ${JSON.stringify(tokens, null, 2)}

export const MANIFEST_THEME_COLOR = '${tokens.light.paper}'
`,
)

const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'))
if (manifest.theme_color.toLowerCase() !== tokens.light.paper) {
  throw new Error(
    `manifest theme_color (${manifest.theme_color}) does not match the light paper token (${tokens.light.paper})`,
  )
}
if (manifest.background_color.toLowerCase() !== tokens.light.paper) {
  throw new Error(
    `manifest background_color (${manifest.background_color}) does not match the light paper token (${tokens.light.paper})`,
  )
}

console.log('Tokens in sync: tokens.generated.ts and the DESIGN.md table are up to date.')
